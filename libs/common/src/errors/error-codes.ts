/** Codes a reservation can end with in `failed` (DESIGN.md §4.2). Reported through the reservation status webhook. */
export enum BookingFailureCode {
  PLATFORM_BLOCKED = 'PLATFORM_BLOCKED',
  UNEXPECTED_STEP = 'UNEXPECTED_STEP',
  SLOT_UNAVAILABLE = 'SLOT_UNAVAILABLE',
  CONFIRMATION_MISMATCH = 'CONFIRMATION_MISMATCH',
  OUTCOME_UNKNOWN = 'OUTCOME_UNKNOWN',
  PLATFORM_UNAVAILABLE = 'PLATFORM_UNAVAILABLE',
  SCRIPT_FAILED = 'SCRIPT_FAILED',
  INTERNAL_ERROR = 'INTERNAL_ERROR',
}

export function isBookingFailureCode(value: string): value is BookingFailureCode {
  return (Object.values(BookingFailureCode) as string[]).includes(value);
}
